    private void deleteBTNActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_deleteBTNActionPerformed
        // TODO add your handling code here:
        String id = idDTF.getText().trim();  //Get and clean the input ID (remove spaces before/after)

        if(id.isEmpty()){ // To check whether id fields is empty or not
            JOptionPane.showMessageDialog(null, "Please enter an ID "); //To display popup when idTF field is empty
            return;
        }

        boolean success = manager.deleteExpense(id); //To test whether id has been found in the list or not
        if(success){
            JOptionPane.showMessageDialog(null, "Expense with ID: " + id + "\n" + "deleted successfully.");
        }else{
            JOptionPane.showMessageDialog(null, "No expense found with id " + id);
        }
        idDTF.setText("");
    }//GEN-LAST:event_deleteBTNActionPerformed

