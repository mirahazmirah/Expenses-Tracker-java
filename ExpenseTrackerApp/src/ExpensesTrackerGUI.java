    private void addBTNActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_addBTNActionPerformed
        
        // Generate ID for new expense (got from expense class)
        String id = manager.generateID();
        
        //Get user input from text fields
        String date = dateTF.getText();
        String category = getSelectedCategoryTabAdd();
        //Convert String to double
        double amount = Double.parseDouble(amountTF.getText());
        String description = descTF.getText();

        //Create a new expense with entered data from user
        Expense e = new Expense (id, date, category, amount, description); //
        
        //Popup message for confirmation that data has been added
        JOptionPane.showMessageDialog(null, "Expense added! Click Reset to enter another");
        
        //Add the new expense to the list
        manager.addExpense(e);
        
        //Save the updated list to a file name expense.txt
        manager.saveToFile("expenses.text");
        
        //Update view area with all expenses
        String summary = manager.displayAllExpenses();
        viewTA.setText(summary);
        
        //Update total money spent and display in moneyOutTA field
        String total = manager.calculateTotal();
        moneyOutTA.setText(total);
    }//GEN-LAST:event_addBTNActionPerformed

