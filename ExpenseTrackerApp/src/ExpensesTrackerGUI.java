    private void searchSBTNActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_searchSBTNActionPerformed

        String category = getSelectedCategoryTabSearch(); // Get category from method getSelectedCategoryTabSearch()

        if (category == null) { //If category is empty
            JOptionPane.showMessageDialog(null, "Please select a category."); // To display popup when category field is empty
            return;
        }

        List<Expense> filtered = manager.searchByCategory(category); 

        if (filtered.isEmpty()) {
            JOptionPane.showMessageDialog(null, "No expenses found in category " + getSelectedCategoryTabSearch());
            recordCTA.setText("");
            totalCTA.setText("");
        } else {
            recordCTA.setText(""); // kosongkan dulu
            for (Expense e : filtered) {
                // Display record
                recordCTA.append("ID: " + e.getId() +
                    "\nDate: " + e.getDate() +
                    "\nCategory: " + e.getCategory() +
                    "\nAmount: RM" + e.getAmount() +
                    "\nDescription: " + e.getDescription() +
                    "\n" + "\n");
            }
        }
    }//GEN-LAST:event_searchSBTNActionPerformed

