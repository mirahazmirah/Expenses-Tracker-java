    private void searchEBTNActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_searchEBTNActionPerformed

        // TODO add your handling code here:
        String id = idTF.getText().trim();  // get the ID from text field
        Expense exp = manager.findById(id); // call your method to find expense

        if (exp != null) {
            // Expense found and display details in text fields and enable editing
            editDateTF.setText(exp.getDate());
            editCategoryTF.setText(exp.getCategory());
            editAmountTF.setText(String.valueOf(exp.getAmount()));
            editDescTF.setText(exp.getDescription());

            editDateTF.setEnabled(true);
            editCategoryTF.setEnabled(true);
            editAmountTF.setEnabled(true);
            editDescTF.setEnabled(true);
            saveBTN.setEnabled(true);
        } else {
            // Not found so display popup maessage notify user and disable editing fields
            JOptionPane.showMessageDialog(null, "Expense ID not found.");

            editDateTF.setText("");
            editCategoryTF.setText("");
            editAmountTF.setText("");
            editDescTF.setText("");

            editDateTF.setEnabled(false);
            editCategoryTF.setEnabled(false);
            editAmountTF.setEnabled(false);
            editDescTF.setEnabled(false);
            saveBTN.setEnabled(false);
        }
    }//GEN-LAST:event_searchEBTNActionPerformed

    private void saveBTNActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_saveBTNActionPerformed
        String id = idTF.getText().trim();
        Expense exp = manager.findById(id); //call method from expense manager class

        if(exp != null){ 
            //Update expenses that entered by user
            exp.setDate(editDateTF.getText().trim());
            exp.setCategory(editCategoryTF.getText().trim());
            exp.setAmount(Double.parseDouble(editAmountTF.getText().trim()));
            exp.setDescription(editDescTF.getText().trim());

            try {
                double amount = Double.parseDouble(editAmountTF.getText().trim());
                exp.setAmount(amount);
                JOptionPane.showMessageDialog(null, "Nice! Budget updated successfully");

            } catch (NumberFormatException exNum){
                JOptionPane.showMessageDialog(null, "Invalid  id. Please enter a valid id");

            }
        }else{
            JOptionPane.showMessageDialog(null, "No matching expense to update");
        }
    }//GEN-LAST:event_saveBTNActionPerformed

